
import PDFDocument from "pdfkit";

export interface ReportData {
  queryId: string;
  question: string;
  status: string;
  answer: unknown;
  estimate: unknown;
}

export function createReportPdf(data: ReportData): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "A4",
      margin: 50,
      info: {
        Title: "SatQuery AI Analysis Report",
        Author: "SatQuery AI",
      },
    });

    const chunks: Buffer[] = [];

    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    doc.fontSize(22).text("SatQuery AI", { align: "center" });
    doc.moveDown(0.5);
    doc.fontSize(15).text("Satellite Analysis Report", { align: "center" });
    doc.moveDown(2);

    doc.fontSize(11);
    doc.text(`Query ID: ${data.queryId}`);
    doc.text(`Generated: ${new Date().toLocaleString()}`);
    doc.text(`Status: ${data.status}`);
    doc.moveDown();

    doc.fontSize(14).text("User Question");
    doc.moveDown(0.4);
    doc.fontSize(11).text(data.question || "Not available");
    doc.moveDown();

    doc.fontSize(14).text("Analysis Answer");
    doc.moveDown(0.4);
    doc.fontSize(11).text(formatValue(data.answer));
    doc.moveDown();

    doc.fontSize(14).text("Estimate");
    doc.moveDown(0.4);
    doc.fontSize(11).text(formatValue(data.estimate));

    doc.moveDown(2);
    doc.fontSize(9).fillColor("gray").text(
      "Generated by SatQuery AI. Interpret results in the context of the source imagery, analysis method, and uncertainty.",
      { align: "left" },
    );

    doc.end();
  });
}

function formatValue(value: unknown): string {
  if (value == null) return "Not available";
  if (typeof value === "string") return value;
  try {
    return JSON.stringify(value, null, 2);
  } catch {
    return String(value);
  }
}
