"""Generate the landing-page globe's land mask (decorative only).

    python frontend/scripts/build_landmask.py <ne_110m_land.geojson> engine/aeqe/data/india_districts.json frontend/src/components/three/landmask.ts

Rasterises Natural Earth 110 m land (public domain) and India's outline (union of the
geoBoundaries districts already shipped with the engine) onto a 0.5° grid and writes a
run-length-encoded string: per row, runs of "<value><length>," where value 0 = ocean,
1 = land, 2 = India.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import shapely
from shapely.geometry import shape
from shapely.ops import unary_union

RES = 0.5


def main(land_path: str, india_path: str, out_path: str) -> None:
    land = unary_union([shape(f["geometry"]) for f in json.loads(Path(land_path).read_text(encoding="utf-8"))["features"]])
    india = unary_union([shape(d["geometry"]).buffer(0) for d in json.loads(Path(india_path).read_text(encoding="utf-8"))["districts"]])
    india = india.buffer(0.15).buffer(-0.1)   # close tiny gaps between simplified districts
    shapely.prepare(land)
    shapely.prepare(india)
    w, h = int(360 / RES), int(180 / RES)
    lon = -180 + (np.arange(w) + 0.5) * RES
    lat = 90 - (np.arange(h) + 0.5) * RES
    X, Y = np.meshgrid(lon, lat)
    grid = shapely.contains_xy(land, X, Y).astype(np.uint8)
    grid[shapely.contains_xy(india, X, Y)] = 2
    rows = []
    for r in grid:
        runs, cur, n = [], int(r[0]), 0
        for v in r:
            if int(v) == cur:
                n += 1
            else:
                runs.append(f"{cur}{n}")
                cur, n = int(v), 1
        runs.append(f"{cur}{n}")
        rows.append(",".join(runs))
    body = "|".join(rows)
    Path(out_path).write_text(
        "// Generated by frontend/scripts/build_landmask.py — Natural Earth 110 m land (public domain) + India (geoBoundaries, ODbL).\n"
        "// 0.5° grid, rows north→south; per row runs of <value><length>: 0 ocean, 1 land, 2 India. Decorative use only.\n"
        f"export const MASK_W = {w};\nexport const MASK_H = {h};\nexport const MASK_RLE = \"{body}\";\n",
        encoding="utf-8")
    print(f"{w}x{h}, land {(grid > 0).mean():.1%}, india cells {(grid == 2).sum()}, {len(body) / 1024:.1f} KB")


if __name__ == "__main__":
    main(*sys.argv[1:4])
